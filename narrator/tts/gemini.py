LANG_NAMES = {"he": "Modern Israeli Hebrew", "en": "English", "ar": "Arabic", "ru": "Russian", "fr": "French",
              "de": "German", "es": "Spanish", "it": "Italian", "pt": "Portuguese"}


def style_instruction(lang: str) -> str:
    """Narration direction given to the model (not spoken)."""
    name = LANG_NAMES.get(lang, "the language of the text")
    extra = ""
    if lang == "he":
        extra = (" The text is unvowelled Hebrew: work out the intended word and its correct pronunciation and"
                 " stress from the full sentence context. Read acronyms the way Israelis say them and numbers"
                 " in correct Hebrew.")
    return (f"Read the following text aloud in fluent, natural {name}, like an experienced lecturer reading study"
            f" material to a student: calm, clear and warm, with natural phrasing and intonation and a moderate,"
            f" steady pace. Read every word exactly as written, without adding, skipping or changing anything.{extra}")


def pcm_to_mp3(pcm: bytes, rate: int) -> Optional[bytes]:
    try:
        import lameenc
    except Exception:
        return None
    enc = lameenc.Encoder()
    enc.set_bit_rate(64)
    enc.set_in_sample_rate(rate)
    enc.set_channels(1)
    enc.set_quality(2)
    return bytes(enc.encode(pcm) + enc.flush())


def pcm_to_wav(pcm: bytes, rate: int) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(rate)
        wf.writeframes(pcm)
    return buf.getvalue()


class GeminiProvider(TTSProvider):
    info = ProviderInfo(
        id="gemini",
        name="Google Gemini voices (most natural; understands context)",
        free=True,
        cloud=True,
        requires_key=True,
        word_timing=False,
        privacy=("The passages being read are sent to Google's Gemini API with your key. On the free tier Google may"
                 " use submitted content to improve its products; with billing enabled it does not."),
        verified=("Request/response handling, model discovery, rate-limit retries and audio encoding are tested against"
                  " a simulated service; live synthesis was not reachable from the development environment."),
    )

    prefetch_limit = 1  # free-tier quotas are small: keep at most one chunk ahead

    def __init__(self, transport: Optional[httpx.AsyncBaseTransport] = None):
        self.key: Optional[str] = None
        self.model_pref: str = ""
        self.transport = transport
        self._model: Optional[str] = None
        self._model_time = 0.0

    def configure(self, settings: dict) -> None:
        key = (settings.get("gemini_api_key") or "").strip() or None
        pref = (settings.get("gemini_model") or "").strip()
        if key != self.key or pref != self.model_pref:
            self._model = None
        self.key = key
        self.model_pref = pref

    def available(self) -> tuple:
        if not self.key:
            return False, "Add a free Gemini API key in Settings (get one at aistudio.google.com)."
        return True, ""

    @property
    def version(self) -> str:
        return "gemini-1:" + (self._model or self.model_pref or "auto")

    def _client(self) -> httpx.AsyncClient:
        return httpx.AsyncClient(timeout=120, transport=self.transport, headers={"x-goog-api-key": self.key or ""})

    async def list_voices(self) -> List[Voice]:
        if not self.key:
            return []  # offered only once a key is saved
        return [Voice(id=f"gemini:{n}", provider="gemini", name=n, locale="mul",
                      gender="Female" if "female" in d else "Male", description=d) for n, d in VOICES]

    async def models(self) -> List[str]:
        names: List[str] = []
        page = None
        async with self._client() as c:
            for _ in range(10):
                params = {"pageSize": 200}
                if page:
                    params["pageToken"] = page
                r = await c.get(f"{API}/models", params=params)
                if r.status_code != 200:
                    raise TTSError(_error_message(r), retryable=False)
                data = r.json()
                for m in data.get("models", []):
                    name = m.get("name", "").split("/")[-1]
                    if "tts" in name and "generateContent" in m.get("supportedGenerationMethods", ["generateContent"]):
                        names.append(name)
                page = data.get("nextPageToken")
                if not page:
                    break
        return names

    async def model(self) -> str:
        if self.model_pref:
            return self.model_pref
        if self._model and time.time() - self._model_time < 6 * 3600:
            return self._model
        names = await self.models()
        if not names:
            raise TTSError("Your Gemini API key has no text-to-speech model available.", retryable=False)

        def rank(n: str):
            for i, p in enumerate(PREFERRED_MODELS):
                if n.startswith(p):
                    return (i, n)
            return (len(PREFERRED_MODELS), n)

        self._model = sorted(names, key=rank)[0]
        self._model_time = time.time()
        log.info("Gemini TTS model: %s", self._model)
        return self._model

    async def synthesize(self, text: str, voice: str, lang: str, rate: int = 0, pitch: int = 0) -> SynthResult:
        ok, reason = self.available()
        if not ok:
            raise TTSError(reason, retryable=False)
        model = await self.model()
        name = voice.split(":", 1)[-1]
        body = {
            "contents": [{"role": "user", "parts": [{"text": f"{style_instruction(lang)}\n\n{text}"}]}],
            "generationConfig": {
                "responseModalities": ["AUDIO"],
                "speechConfig": {"voiceConfig": {"prebuiltVoiceConfig": {"voiceName": name}}},
            },
        }
        last = ""
        for attempt in range(4):
            try:
                async with self._client() as c:
                    r = await c.post(f"{API}/models/{model}:generateContent", json=body)
            except httpx.HTTPError as exc:
                last = f"Could not reach Google's Gemini API: {exc}"
                await asyncio.sleep(1.5 * (attempt + 1))
                continue
            if r.status_code == 200:
                return self._parse(r.json())
            if r.status_code == 429 or r.status_code >= 500:
                wait = _retry_delay(r) or 2.0 * (attempt + 1)
                last = _error_message(r)
                if wait > 40:
                    break
                await asyncio.sleep(wait)
                continue
            raise TTSError(_error_message(r), retryable=False)
        if "quota" in last.lower() or "rate" in last.lower() or "429" in last:
            last = ("Gemini free-tier limit reached. Narration will continue when the limit resets, or enable"
                    " billing on your Google AI Studio key for uninterrupted use. (" + last[:200] + ")")
        raise TTSError(last or "Gemini speech generation failed.")

    @staticmethod
    def _parse(data: dict) -> SynthResult:
        try:
            parts = data["candidates"][0]["content"]["parts"]
            inline = next(p.get("inlineData") or p.get("inline_data") for p in parts if p.get("inlineData") or p.get("inline_data"))
        except Exception:
            reason = (data.get("candidates") or [{}])[0].get("finishReason") or data.get("promptFeedback") or "no audio returned"
            raise TTSError(f"Gemini returned no audio ({reason}).")
        pcm = base64.b64decode(inline["data"])
        mime = inline.get("mimeType") or inline.get("mime_type") or "audio/L16;rate=24000"
        m = re.search(r"rate=(\d+)", mime)
        rate = int(m.group(1)) if m else 24000
        duration = len(pcm) / (2 * rate)
        mp3 = pcm_to_mp3(pcm, rate)
        if mp3:
            return SynthResult(audio=mp3, ext="mp3", mime="audio/mpeg", duration=duration, boundaries=[])
        return SynthResult(audio=pcm_to_wav(pcm, rate), ext="wav", mime="audio/wav", duration=duration, boundaries=[])


def _error_message(r: httpx.Response) -> str:
    try:
        err = r.json().get("error", {})
        msg = err.get("message") or r.text[:300]
        status = err.get("status", "")
    except Exception:
        msg, status = r.text[:300], ""
    if r.status_code in (400, 403) and ("API key" in msg or "API_KEY" in msg or status == "PERMISSION_DENIED"):
        return "Google rejected the Gemini API key. Check it in Settings. (" + msg[:200] + ")"
    return f"Gemini API error {r.status_code}: {msg}"


def _retry_delay(r: httpx.Response) -> Optional[float]:
    try:
        for d in r.json().get("error", {}).get("details", []):
            if "retryDelay" in d:
                return float(str(d["retryDelay"]).rstrip("s"))
    except Exception:
        pass
    ra = r.headers.get("retry-after")
    try:
        return float(ra) if ra else None
    except ValueError:
        return None
