"""Google Gemini speech generation (language-model based voices).

Why: unvowelled Hebrew is ambiguous ("ספר" = book / barber / counted / border).
Classic TTS front-ends guess word by word.  Gemini voices are generated by a
large language model that reads the whole sentence, so it picks the intended
word from context and produces natural, human-like intonation.

* Needs a Gemini API key (free from Google AI Studio; the free tier is
  rate-limited).  Entered in Settings and stored only on this computer.
* The voices are multilingual: the same voice reads Hebrew, English and many
  other languages.
* The service returns no word timings, so highlighting is sentence-level and
  marked as estimated.
* Available TTS models are discovered at runtime, so renamed preview models
  do not break the integration.
"""
